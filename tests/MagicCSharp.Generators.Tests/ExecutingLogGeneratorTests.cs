    [Fact]
    public void LogExecuting_WritesADecoratorThatLogsEachArgumentThenCallsTheUseCase()
    {
        // Act
        var generatorRunResult = RunExecutingLog("""
                                                 public record PayChargeRequest
                                                 {
                                                     public required decimal Amount { get; init; }
                                                 }

                                                 public interface IPayChargeUseCase : IMagicUseCase
                                                 {
                                                     Task<long> Execute(long chargeId, PayChargeRequest request);
                                                 }

                                                 [LogExecuting]
                                                 public class PayChargeUseCase : IPayChargeUseCase
                                                 {
                                                     public Task<long> Execute(long chargeId, PayChargeRequest request)
                                                     {
                                                         return Task.FromResult(chargeId);
                                                     }
                                                 }
                                                 """);

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.Charges;

                     /// <summary>Writes the Executing: line of PayChargeUseCase, then calls it; registered for its interface in its place.</summary>
                     [global::MagicCSharp.Modules.RegisteredInPlaceOf(typeof(global::Acme.Leasing.Charges.PayChargeUseCase))]
                     file sealed class PayChargeUseCaseExecutingLogDecorator : global::Acme.Leasing.Charges.IPayChargeUseCase
                     {
                         private readonly global::Acme.Leasing.Charges.IPayChargeUseCase payChargeUseCase;

                         private readonly global::Microsoft.Extensions.Logging.ILogger<global::Acme.Leasing.Charges.PayChargeUseCase> logger;

                         public PayChargeUseCaseExecutingLogDecorator(global::Acme.Leasing.Charges.PayChargeUseCase payChargeUseCase, global::Microsoft.Extensions.Logging.ILogger<global::Acme.Leasing.Charges.PayChargeUseCase> logger)
                         {
                             this.payChargeUseCase = payChargeUseCase;
                             this.logger = logger;
                         }

                         public global::System.Threading.Tasks.Task<long> Execute(long chargeId, global::Acme.Leasing.Charges.PayChargeRequest request)
                         {
                             global::Microsoft.Extensions.Logging.LoggerExtensions.LogTrace(this.logger, "Executing: chargeId={chargeId}, request={request}", new object?[] { chargeId, request });
                             return this.payChargeUseCase.Execute(chargeId, request);
                         }
                     }

                     """, generatorRunResult.GeneratedText(PayChargeHintName));
    }

    [Fact]
