                 """;
    }

    private static string UseCaseNamed(string className)
    {
        return $$"""
                 public interface I{{className}} : IMagicUseCase
                 {
                     Task Execute(long chargeId);
                 }

                 [LogExecuting]
                 public class {{className}} : I{{className}}
                 {
                     public Task Execute(long chargeId)
                     {
                         return Task.CompletedTask;
                     }
                 }
                 """;
    }

    private static string SubjectSource(string useCaseSource)
    {
        return """
               using System.IO;
               using System.Threading;
               using System.Threading.Tasks;
               using MagicCSharp.UseCases;

               namespace Acme.Leasing.Charges;


               """ + useCaseSource;
    }

    private static GeneratorRunRequest ExecutingLogRequest(string useCaseSource)
    {
        return new GeneratorRunRequest
        {
            SourceFiles = [GeneratorHarness.Subject(SubjectSource(useCaseSource))],
            OtherGenerators = [new ExecutingLogGenerator()],
            AdditionalReferences = [LoggingReference],
        };
    }

    private static GeneratorRunResult RunExecutingLog(string useCaseSource)
    {
        return GeneratorHarness.Run(ExecutingLogRequest(useCaseSource));
    }

    private static string[] Refusals(string useCaseSource)
    {
        var generatorRunResult = RunExecutingLog(useCaseSource);
        Assert.DoesNotContain(generatorRunResult.GeneratedFiles, generatedFile => generatedFile.Path.EndsWith(".ExecutingLog.g.cs", StringComparison.Ordinal));
        return generatorRunResult.Diagnostics;
    }

    private static void AssertSingleRefusal(string[] diagnostics, string diagnosticId, string messageStart)
    {
        var diagnostic = Assert.Single(diagnostics);
        Assert.StartsWith(diagnosticId + " Subject.cs:", diagnostic);
        Assert.Contains(messageStart, diagnostic);
    }
