        Assert.Contains("LogTrace(this.logger, \"Executing: leaseId={leaseId}\", new object?[] { leaseId });", decoratorText);
        Assert.Contains("LogTrace(this.logger, \"Executing: leaseId={leaseId}, amount={amount}\", new object?[] { leaseId, amount });", decoratorText);
    }

