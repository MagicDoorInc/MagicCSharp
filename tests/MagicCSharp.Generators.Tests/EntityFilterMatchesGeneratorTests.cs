namespace MagicCSharp.Generators.Tests;

public class EntityFilterMatchesGeneratorTests
{
    private const string FilterHintName = "Acme.Shipping.ShipmentFilter.FilterMatches.g.cs";

    private const string ControlFilterHintName = "Acme.Shipping.ShipmentControlFilter.FilterMatches.g.cs";

    private const string Usings = """
                                  using System;
                                  using System.Collections.Generic;
                                  using MagicCSharp.Infrastructure;

                                  """;

    private const string ShipmentTypes = """
                                         namespace Acme.Shipping;

                                         public enum ShipmentStatus
                                         {
                                             Booked,
                                             Delivered,
                                         }

                                         public record Shipment
                                         {
                                             public required long Id { get; init; }
                                             public required long TenantId { get; init; }
                                             public required ShipmentStatus Status { get; init; }
                                             public long? CarrierId { get; init; }
                                             public required string TrackingCode { get; init; }
                                             public DateTimeOffset? Delivered { get; init; }
                                             public required DateTimeOffset Created { get; init; }
                                         }


                                         """;

    // A filter that gets Matches, beside the one under test, which proves the generator ran.
    private const string ControlFilter = """

                                         [GenerateMatches]
                                         public partial class ShipmentControlFilter : IEntityFilter<Shipment>
                                         {
                                             public List<long>? Ids { get; init; }
                                         }

                                         """;

    [Fact]
    public void FilterMatches_WritesMatches_WithOneCheckPerFieldInFilterOrder()
    {
        // Arrange
        const string source = Usings + ShipmentTypes + """
                                                       [GenerateMatches]
                                                       public partial class ShipmentFilter : IEntityFilter<Shipment>
                                                       {
                                                           public List<long>? Ids { get; init; }
                                                           public long? TenantId { get; init; }
                                                           public List<ShipmentStatus>? Statuses { get; init; }
                                                           public bool? IsDelivered { get; init; }
                                                           public ComparableRange<DateTimeOffset>? Created { get; init; }
                                                       }
                                                       """;

        // Act
        var generatorRunResult = RunClean(source);

        // Assert
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Shipping;

                     partial class ShipmentFilter
                     {
                         public bool Matches(global::Acme.Shipping.Shipment entity)
                         {
                             if (!global::MagicCSharp.Infrastructure.FilterMatching.MatchesListFilter<long>(Ids, entity.Id))
                             {
                                 return false;
                             }

                             if (!global::MagicCSharp.Infrastructure.FilterMatching.MatchesNullableValueFilter<long>(TenantId, entity.TenantId))
                             {
                                 return false;
                             }

                             if (!global::MagicCSharp.Infrastructure.FilterMatching.MatchesListFilter<global::Acme.Shipping.ShipmentStatus>(Statuses, entity.Status))
                             {
                                 return false;
                             }

                             if (!global::MagicCSharp.Infrastructure.FilterMatching.MatchesNullablePresenceFilter<global::System.DateTimeOffset>(IsDelivered, entity.Delivered))
                             {
                                 return false;
                             }

                             if (!global::MagicCSharp.Infrastructure.FilterMatching.MatchesComparableRangeFilter<global::System.DateTimeOffset>(Created, entity.Created))
                             {
                                 return false;
                             }

                             return true;
                         }
                     }

                     """, generatorRunResult.GeneratedText(FilterHintName));
    }

    [Fact]
    public void FilterMatches_ChecksAStringList_OnARecordFilter()
    {
        // Arrange
        const string source = Usings + ShipmentTypes + """
                                                       [GenerateMatches]
