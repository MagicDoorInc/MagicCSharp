        Assert.Contains("global::MagicCSharp.Infrastructure.FilterMatching.MatchesListFilter(TrackingCodes, entity.TrackingCode)", matches);
    }

    [Fact]
    public void FilterMatches_CallsMatchesCustomFilterLast_WhenItReadsTheCustomField()
    {
        // Arrange
        const string source = Usings + ShipmentTypes + """
                                                       [GenerateMatches]
                                                       public partial class ShipmentFilter : IEntityFilter<Shipment>
                                                       {
                                                           public long? TenantId { get; init; }
                                                           public string? TrackingCodeContains { get; init; }

                                                           private partial bool MatchesCustomFilter(Shipment entity)
                                                           {
                                                               return TrackingCodeContains == null || entity.TrackingCode.Contains(TrackingCodeContains);
                                                           }
                                                       }
                                                       """;

        // Act
        var generatorRunResult = RunClean(source);

        // Assert
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Shipping;

                     partial class ShipmentFilter
                     {
                         public bool Matches(global::Acme.Shipping.Shipment entity)
                         {
                             if (!global::MagicCSharp.Infrastructure.FilterMatching.MatchesNullableValueFilter<long>(TenantId, entity.TenantId))
                             {
                                 return false;
                             }

                             return MatchesCustomFilter(entity);
                         }

                         private partial bool MatchesCustomFilter(global::Acme.Shipping.Shipment entity);
                     }

                     """, generatorRunResult.GeneratedText(FilterHintName));
    }

    [Fact]
    public void FilterMatches_ReportsMCS1304_WhenNoMatchesCustomFilterIsWritten()
    {
        // Arrange
        const string source = Usings + ShipmentTypes + """
