    [Fact]
    public void GenerateInterface_ReusesItsOutput_WhenAnUnrelatedFileChanges()
    {
        // Arrange
        var generatorRunRequest = new GeneratorRunRequest
        {
            SourceFiles =
            [
                GeneratorHarness.Subject("""
                                         using System.Threading.Tasks;
                                         using MagicCSharp.UseCases;

                                         namespace Acme.Leasing.Charges;

                                         [GenerateInterface]
                                         public partial class PayChargeUseCase
                                         {
                                             public Task Execute(long chargeId)
                                             {
                                                 return Task.CompletedTask;
                                             }
                                         }
                                         """),
            ],
        };
        var compilation = GeneratorHarness.CreateCompilation(generatorRunRequest.SourceFiles);
        var driver = GeneratorHarness.CreateDriver(generatorRunRequest, true).RunGenerators(compilation);
        var unrelatedFile = CSharpSyntaxTree.ParseText("namespace Acme.Leasing.Charges; public class ChargeNote { }",
            (CSharpParseOptions)compilation.SyntaxTrees.First().Options, "ChargeNote.cs");

        // Act
        driver = driver.RunGenerators(compilation.AddSyntaxTrees(unrelatedFile));

        // Assert
        var outputReasons = driver.GetRunResult()
            .Results.Single(result => result.Generator.GetGeneratorType() == typeof(GenerateInterfaceGenerator))
            .TrackedOutputSteps.SelectMany(trackedStep => trackedStep.Value)
            .SelectMany(step => step.Outputs)
            .Select(output => output.Reason)
            .ToArray();
        Assert.NotEmpty(outputReasons);
        Assert.All(outputReasons, reason => Assert.Equal(IncrementalStepRunReason.Cached, reason));
    }

    private static string[] Refusals(string useCaseSource, string? markerInterfaceSetting = null)
    {
        var source = """
                     using System.Threading.Tasks;
                     using MagicCSharp.UseCases;

                     namespace Acme.Leasing.Charges;


                     """ + useCaseSource;
        var generatorRunResult = GeneratorHarness.Run(new GeneratorRunRequest
        {
            SourceFiles = [GeneratorHarness.Subject(source)],
            MarkerInterfaceSetting = markerInterfaceSetting,
        });
        Assert.Empty(generatorRunResult.GeneratedFiles);
        return generatorRunResult.Diagnostics;
    }

    private static string[] InterfaceMethods(GeneratorRunResult generatorRunResult, string interfaceMetadataName)
    {
        var generatedInterface = generatorRunResult.OutputCompilation.GetTypeByMetadataName(interfaceMetadataName)!;
        Assert.Equal(TypeKind.Interface, generatedInterface.TypeKind);
        return generatedInterface.GetMembers()
            .OfType<IMethodSymbol>()
            .Select(method => method.Name + "(" + string.Join(", ", method.Parameters.Select(parameter => parameter.Type.ToDisplayString())) + ")")
            .ToArray();
    }
