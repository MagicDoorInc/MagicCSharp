    private const string SignLeaseHintName = "Acme.Leasing.Leases.SignLeaseUseCase.Interface.g.cs";

    [Fact]
    public void GenerateInterface_WritesTheInterfaceAndImplementsIt_ForASignLeaseShapedUseCase()
    {
        // Arrange
        const string source = """
                              using System.Threading.Tasks;
                              using MagicCSharp.UseCases;

                              namespace Acme.Leasing.Leases;

                              public record SignLeaseRequest
                              {
                                  public required long PropertyId { get; init; }
                              }

                              public record SignLeaseResult
                              {
                                  public required long LeaseId { get; init; }
                              }

                              /// <summary>Signing is finding the property, creating the lease and raising its charges.</summary>
                              [GenerateInterface]
                              public partial class SignLeaseUseCase
                              {
                                  /// <summary>Signs the lease and raises its day-one charges.</summary>
                                  /// <param name="request">What the tenant signs.</param>
                                  public async Task<SignLeaseResult> Execute(SignLeaseRequest request)
                                  {
                                      await Task.Yield();
                                      return new SignLeaseResult { LeaseId = request.PropertyId };
                                  }

                                  private static long Unused()
                                  {
                                      return 0;
                                  }
                              }
                              """;

        // Act
        var generatorRunResult = GeneratorHarness.RunClean(source);

        // Assert
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.Leases;

                     public partial interface ISignLeaseUseCase : global::MagicCSharp.UseCases.IMagicUseCase
                     {
                         /// <summary>Signs the lease and raises its day-one charges.</summary>
                         /// <param name="request">What the tenant signs.</param>
                         global::System.Threading.Tasks.Task<global::Acme.Leasing.Leases.SignLeaseResult> Execute(global::Acme.Leasing.Leases.SignLeaseRequest request);
                     }

                     partial class SignLeaseUseCase : global::Acme.Leasing.Leases.ISignLeaseUseCase
                     {
                     }

                     """, generatorRunResult.GeneratedText(SignLeaseHintName));
        var useCaseClass = generatorRunResult.OutputCompilation.GetTypeByMetadataName("Acme.Leasing.Leases.SignLeaseUseCase")!;
        Assert.Contains(useCaseClass.AllInterfaces, implemented => implemented.ToDisplayString() == "Acme.Leasing.Leases.ISignLeaseUseCase");
        Assert.Contains(useCaseClass.AllInterfaces, implemented => implemented.ToDisplayString() == "MagicCSharp.UseCases.IMagicUseCase");
    }

