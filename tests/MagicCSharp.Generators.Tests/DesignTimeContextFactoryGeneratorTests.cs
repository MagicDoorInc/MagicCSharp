using MagicCSharp.Data.EntityFramework;
using MagicCSharp.Data.Postgres;
using MagicCSharp.Generators.Declarations.ContextFactories;
using Microsoft.CodeAnalysis;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Npgsql.EntityFrameworkCore.PostgreSQL.Infrastructure;

namespace MagicCSharp.Generators.Tests;

public class DesignTimeContextFactoryGeneratorTests
{
    private const string Usings = """
                                  using System;
                                  using MagicCSharp.Data.EntityFramework;
                                  using Microsoft.EntityFrameworkCore;
                                  using Microsoft.EntityFrameworkCore.Design;

                                  namespace Acme.Leasing.Data;

                                  """;

    private static readonly MetadataReference[] DataReferences =
    [
        MetadataReference.CreateFromFile(typeof(MigrationsDatabaseAttribute).Assembly.Location),
        MetadataReference.CreateFromFile(typeof(MagicDbContextFactory<>).Assembly.Location),
        MetadataReference.CreateFromFile(typeof(DbContext).Assembly.Location),
        MetadataReference.CreateFromFile(typeof(RelationalDbContextOptionsBuilder<,>).Assembly.Location),
        MetadataReference.CreateFromFile(typeof(NpgsqlDbContextOptionsBuilder).Assembly.Location),
    ];

    [Fact]
    public void ContextFactory_IsGenerated_ForAMarkedContext_AgainstItsMigrationsDatabase()
    {
        // Act
        var generatorRunResult = Run(Usings + """
                                              [MigrationsDatabase("leasing")]
                                              [GenerateDesignTimeFactory]
                                              public class MagicLeasingContext(DbContextOptions<MagicLeasingContext> options) : MagicDbContext(options);
                                              """);

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.Data
                     {
                         /// <summary>
                         ///     Lets dotnet ef build MagicLeasingContext outside the running application, against the database its
                         ///     [MigrationsDatabase] names. Written at each build.
                         /// </summary>
                         public class MagicLeasingContextFactory : global::MagicCSharp.Data.Postgres.MagicDbContextFactory<global::Acme.Leasing.Data.MagicLeasingContext>
                         {
                             public MagicLeasingContextFactory()
                                 : base("leasing")
                             {
                             }
                         }
                     }

                     """.ReplaceLineEndings("\n"), generatorRunResult.GeneratedText("Acme.Leasing.Data.MagicLeasingContextFactory.g.cs"));
    }

    [Fact]
    public void ContextFactory_UsesTheConfiguredBase()
    {
        // Arrange: a factory base with its own defaults, as a codebase with another local port has.
        const string source = Usings + """
                                       public abstract class LocalPortContextFactory<TContext>(string databaseName, string port = "35432") : IDesignTimeDbContextFactory<TContext>
                                           where TContext : DbContext
                                       {
                                           public TContext CreateDbContext(string[] args)
                                           {
                                               throw new NotSupportedException(databaseName + port);
                                           }
                                       }

                                       [MigrationsDatabase("leasing")]
                                       [GenerateDesignTimeFactory]
                                       public class LeasingContext(DbContextOptions<LeasingContext> options) : DbContext(options);
                                       """;

        // Act
        var generatorRunResult = Run(source, "Acme.Leasing.Data.LocalPortContextFactory`1");

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.Contains("public class LeasingContextFactory : global::Acme.Leasing.Data.LocalPortContextFactory<global::Acme.Leasing.Data.LeasingContext>",
            generatorRunResult.GeneratedText("Acme.Leasing.Data.LeasingContextFactory.g.cs"));
    }

    [Fact]
    public void ContextFactory_IsSkipped_WhenTheProjectWritesItsOwn()
    {
        // Act
        var generatorRunResult = Run(Usings + """
                                              [MigrationsDatabase("leasing_vector")]
                                              [GenerateDesignTimeFactory]
                                              public class LeasingVectorContext(DbContextOptions<LeasingVectorContext> options) : MagicDbContext(options);

                                              public class LeasingVectorContextFactory : IDesignTimeDbContextFactory<LeasingVectorContext>
                                              {
                                                  public LeasingVectorContext CreateDbContext(string[] args)
                                                  {
                                                      throw new NotSupportedException();
                                                  }
                                              }
                                              """);

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.DoesNotContain(generatorRunResult.GeneratedFiles, generatedFile => generatedFile.Path.EndsWith("Factory.g.cs", StringComparison.Ordinal));
    }

    [Fact]
    public void ContextFactory_IsNotGenerated_ForAContextWithOnlyMigrationsDatabase()
    {
        // Act: partial and naming its database, but not marked.
        var generatorRunResult = Run(Usings + """
                                              [MigrationsDatabase("leasing")]
                                              public partial class MagicLeasingContext(DbContextOptions<MagicLeasingContext> options) : MagicDbContext(options);
                                              """);

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.Empty(generatorRunResult.GeneratedFiles);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1611_ForAMarkedContextWithoutMigrationsDatabase()
    {
        // Act
        var diagnostic = SingleRefusal(Usings + """
                                                [GenerateDesignTimeFactory]
                                                public class MagicLeasingContext(DbContextOptions<MagicLeasingContext> options) : MagicDbContext(options);
                                                """);

        // Assert
        Assert.Equal("MCS1611 Subject.cs:8 'MagicLeasingContext' has [GenerateDesignTimeFactory] but no [MigrationsDatabase]; add " +
                     "[MigrationsDatabase(\"…\")] naming the database the factory connects to", diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1602_ForABlankDatabaseName()
    {
        // Act
        var diagnostic = SingleRefusal(Usings + """
                                                [MigrationsDatabase("  ")]
                                                [GenerateDesignTimeFactory]
                                                public class MagicLeasingContext(DbContextOptions<MagicLeasingContext> options) : MagicDbContext(options);
                                                """);

        // Assert
        Assert.Equal("MCS1602 Subject.cs:9 'MagicLeasingContext' has [MigrationsDatabase] with a blank name; name the database its migrations target", diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1603_WhenTheBaseTypeIsNotInTheCompilation()
    {
        // Act
        var diagnostic = SingleRefusal(LeasingContextSource, "Acme.Shared.MissingContextFactory`1");

        // Assert
        Assert.StartsWith("MCS1603 Subject.cs:9 The design-time factory of 'MagicLeasingContext' is not generated: base type 'Acme.Shared.MissingContextFactory`1' is not in the compilation",
            diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1604_WhenTheBaseTypeHasNoDatabaseNameConstructor()
    {
        // Arrange
        const string source = LeasingContextSource + """


                                                     public abstract class PortOnlyContextFactory<TContext>(int port) : IDesignTimeDbContextFactory<TContext>
                                                         where TContext : DbContext
                                                     {
                                                         public TContext CreateDbContext(string[] args)
                                                         {
                                                             throw new NotSupportedException(port.ToString());
                                                         }
                                                     }
                                                     """;

        // Act
        var diagnostic = SingleRefusal(source, "Acme.Leasing.Data.PortOnlyContextFactory`1");

        // Assert
        Assert.StartsWith("MCS1604 Subject.cs:9 The design-time factory of 'MagicLeasingContext' is not generated: base type " +
                          "'Acme.Leasing.Data.PortOnlyContextFactory`1' has no constructor taking the database name first", diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1605_WhenTheContextMissesTheBasesConstraint()
    {
        // Act: MagicCSharp's Postgres factory takes only a MagicDbContext.
        var diagnostic = SingleRefusal(Usings + """
                                                [MigrationsDatabase("leasing")]
                                                [GenerateDesignTimeFactory]
                                                public class PlainLeasingContext(DbContextOptions<PlainLeasingContext> options) : DbContext(options);
                                                """);

        // Assert
        Assert.Equal("MCS1605 Subject.cs:9 The design-time factory of 'PlainLeasingContext' is not generated: " +
                     "'MagicCSharp.Data.Postgres.MagicDbContextFactory`1' requires its context to be a 'MagicCSharp.Data.EntityFramework.MagicDbContext'",
            diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1606_ForANestedContext()
    {
        // Act
        var diagnostic = SingleRefusal(Usings + """
                                                public class Contexts
                                                {
                                                    [MigrationsDatabase("leasing")]
                                                    [GenerateDesignTimeFactory]
                                                    public class MagicLeasingContext(DbContextOptions<MagicLeasingContext> options) : MagicDbContext(options);
                                                }
                                                """);

        // Assert
        Assert.StartsWith("MCS1606 Subject.cs:11 'global::Acme.Leasing.Data.Contexts.MagicLeasingContext' is nested in another type", diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1607_ForAGenericContext()
    {
        // Act
        var diagnostic = SingleRefusal(Usings + """
                                                [MigrationsDatabase("leasing")]
                                                [GenerateDesignTimeFactory]
                                                public class MagicLeasingContext<TTenant>(DbContextOptions options) : MagicDbContext(options);
                                                """);

        // Assert
        Assert.Equal("MCS1607 Subject.cs:9 'MagicLeasingContext' is generic; write its IDesignTimeDbContextFactory by hand", diagnostic);
    }

    [Fact]
    public void ContextFactory_ReportsMCS1608_ForAnAbstractContext()
    {
        // Act
        var diagnostic = SingleRefusal(Usings + """
                                                [MigrationsDatabase("leasing")]
                                                [GenerateDesignTimeFactory]
                                                public abstract class MagicLeasingContext(DbContextOptions options) : MagicDbContext(options);
                                                """);

        // Assert
        Assert.StartsWith("MCS1608 Subject.cs:9 'MagicLeasingContext' is abstract", diagnostic);
    }

    private const string LeasingContextSource = Usings + """
                                                         [MigrationsDatabase("leasing")]
                                                         [GenerateDesignTimeFactory]
                                                         public class MagicLeasingContext(DbContextOptions<MagicLeasingContext> options) : MagicDbContext(options);
                                                         """;

    private static string SingleRefusal(string source, string? factoryBase = null)
    {
        var generatorRunResult = Run(source, factoryBase);
        Assert.DoesNotContain(generatorRunResult.GeneratedFiles, generatedFile => generatedFile.Path.EndsWith("Factory.g.cs", StringComparison.Ordinal));
        return Assert.Single(generatorRunResult.Diagnostics);
    }

    private static GeneratorRunResult Run(string source, string? factoryBase = null)
    {
        var buildProperties = new Dictionary<string, string>();
        if (factoryBase != null)
        {
            buildProperties[ContextFactoryBaseSetting.PropertyName] = factoryBase;
        }

        return GeneratorHarness.Run(new GeneratorRunRequest
        {
            SourceFiles = [GeneratorHarness.Subject(source)],
            AdditionalReferences = DataReferences,
            BuildProperties = buildProperties,
            OtherGenerators = [new DesignTimeContextFactoryGenerator()],
        });
    }
}
