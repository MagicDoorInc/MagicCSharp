using MagicCSharp.Generators.Declarations.AssemblyLoading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace MagicCSharp.Generators.Tests;

public class AssemblyLoaderGeneratorTests
{
    private const string HostSource = """
                                      namespace Acme.Leasing.App;

                                      public class LeasingProgram
                                      {
                                      }
                                      """;

    private const string LoaderHintName = "Acme.Leasing.App.AssemblyLoader.g.cs";

    private static readonly MetadataReference ChargesProject = Library("Acme.Leasing.Domains.Charges", """
                                                                                                    namespace Acme.Leasing.Domains.Charges;

                                                                                                    public class LateFeeSchedule<TCharge>
                                                                                                    {
                                                                                                    }

                                                                                                    public class ChargeLateFeeUseCase
                                                                                                    {
                                                                                                    }

                                                                                                    public class AddChargeUseCase
                                                                                                    {
                                                                                                    }
                                                                                                    """);

    private static readonly MetadataReference HandlersProject = Library("Acme.Leasing.Domains.Reminders", """
                                                                                                       namespace Acme.Leasing.Domains.Reminders;

                                                                                                       internal class SendRentReminderHandler
                                                                                                       {
                                                                                                       }
                                                                                                       """);

    private static readonly MetadataReference PdfPackage = Library("Acme.Pdf", """
                                                                              namespace Acme.Pdf;

                                                                              public class PdfRenderer
                                                                              {
                                                                              }
                                                                              """);

    [Fact]
    public void AssemblyLoader_LoadsEachReferencedProjectThroughAPublicType()
    {
        // Act
        var generatedText = RunHost([ChargesProject], "Acme.Leasing.Domains.Charges").GeneratedText(LoaderHintName);

        // Assert: the first non-generic public type by full name stands in for its assembly.
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.App
                     {
                         /// <summary>
                         ///     Loads every project this one references before Main runs, so a scan for use cases and handlers also
                         ///     finds the projects nothing has touched yet. Written from the project references at each build.
                         /// </summary>
                         public static class AssemblyLoader
                         {
                             [global::System.Runtime.CompilerServices.ModuleInitializer]
                             public static void Load()
                             {
                                 _ = typeof(global::Acme.Leasing.Domains.Charges.AddChargeUseCase).Assembly;
                             }
                         }
                     }

                     """.ReplaceLineEndings("\n"), generatedText);
    }

    [Fact]
    public void AssemblyLoader_LoadsAProjectWithoutPublicTypesByName()
    {
        // Act
        var generatedText = RunHost([HandlersProject], "Acme.Leasing.Domains.Reminders").GeneratedText(LoaderHintName);

        // Assert
        Assert.Contains("_ = global::System.Reflection.Assembly.Load(new global::System.Reflection.AssemblyName(\"Acme.Leasing.Domains.Reminders\"));",
            generatedText);
    }

    [Fact]
    public void AssemblyLoader_LeavesPackageReferencesOut()
    {
        // Act: all three are referenced; the build lists the two projects, comma-separated as it writes them.
        var generatedText = RunHost([ChargesProject, HandlersProject, PdfPackage], "Acme.Leasing.Domains.Charges,Acme.Leasing.Domains.Reminders")
            .GeneratedText(LoaderHintName);

        // Assert
        Assert.Contains("global::Acme.Leasing.Domains.Charges.AddChargeUseCase", generatedText);
        Assert.Contains("\"Acme.Leasing.Domains.Reminders\"", generatedText);
        Assert.DoesNotContain("Acme.Pdf", generatedText);
    }

    [Fact]
    public void AssemblyLoader_GeneratesNothing_WhenNotOptedIn()
    {
        // Act
        var generatorRunResult = GeneratorHarness.Run(new GeneratorRunRequest
        {
            SourceFiles = [GeneratorHarness.Subject(HostSource)],
            AdditionalReferences = [ChargesProject],
            BuildProperties = new Dictionary<string, string>
            {
                [AssemblyLoaderSettings.ReferencedProjectsPropertyName] = "Acme.Leasing.Domains.Charges",
                ["RootNamespace"] = "Acme.Leasing.App",
            },
            OtherGenerators = [new AssemblyLoaderGenerator()],
        });

        // Assert
        Assert.Empty(generatorRunResult.GeneratedFiles);
        Assert.Empty(generatorRunResult.Diagnostics);
    }

    [Fact]
    public void AssemblyLoader_ReportsMCS1609_WhenTheProjectAlreadyDeclaresIt()
    {
        // Arrange
        const string hostWithScriptWrittenLoader = HostSource + """


                                                                public static class AssemblyLoader
                                                                {
                                                                    public static void Load()
                                                                    {
                                                                        _ = typeof(Acme.Leasing.Domains.Charges.AddChargeUseCase).Assembly;
                                                                    }
                                                                }
                                                                """;

        // Act
        var generatorRunResult = GeneratorHarness.Run(OptedInRequest(hostWithScriptWrittenLoader, [ChargesProject], "Acme.Leasing.Domains.Charges"));

        // Assert
        Assert.Empty(generatorRunResult.GeneratedFiles);
        var diagnostic = Assert.Single(generatorRunResult.Diagnostics);
        Assert.StartsWith("MCS1609 Subject.cs:", diagnostic);
        Assert.Contains("'Acme.Leasing.App.AssemblyLoader' is declared in this project", diagnostic);
    }

    private static GeneratorRunResult RunHost(MetadataReference[] references, string referencedProjects)
    {
        var generatorRunResult = GeneratorHarness.Run(OptedInRequest(HostSource, references, referencedProjects));
        Assert.Empty(generatorRunResult.Diagnostics);
        return generatorRunResult;
    }

    private static GeneratorRunRequest OptedInRequest(string hostSource, MetadataReference[] references, string referencedProjects)
    {
        return new GeneratorRunRequest
        {
            SourceFiles = [GeneratorHarness.Subject(hostSource)],
            AdditionalReferences = references,
            BuildProperties = new Dictionary<string, string>
            {
                [AssemblyLoaderSettings.OptInPropertyName] = "true",
                [AssemblyLoaderSettings.ReferencedProjectsPropertyName] = referencedProjects,
                ["RootNamespace"] = "Acme.Leasing.App",
            },
            OtherGenerators = [new AssemblyLoaderGenerator()],
        };
    }

    private static MetadataReference Library(string assemblyName, string source)
    {
        var library = CSharpCompilation.Create(assemblyName, [CSharpSyntaxTree.ParseText(source)], GeneratorHarness.DefaultReferences(),
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        return library.ToMetadataReference();
    }
}
