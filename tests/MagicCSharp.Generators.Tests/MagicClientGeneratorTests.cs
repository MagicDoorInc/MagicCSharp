using MagicCSharp.Generators.Clients;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace MagicCSharp.Generators.Tests;

public class MagicClientGeneratorTests
{
    private const string ConventionSubject = """
                                             using System;
                                             using System.Net.Http;
                                             using System.Threading;
                                             using System.Threading.Tasks;
                                             using MagicCSharp.Clients;
                                             using Microsoft.Extensions.Configuration;
                                             using Microsoft.Extensions.DependencyInjection;

                                             [assembly: MagicClientConvention(typeof(Acme.Leasing.Clients.ServiceClientBase), typeof(Acme.Leasing.Clients.ServiceClientRegistration),
                                                 nameof(Acme.Leasing.Clients.ServiceClientRegistration.AddServiceClient))]

                                             namespace Acme.Leasing.Clients;

                                             public abstract class ServiceClientBase(string serviceName)
                                             {
                                                 protected string ServiceName { get; } = serviceName;

                                                 protected Task<TResponse> SendRequestAsync<TResponse>(HttpMethod method, string path, object? body, CancellationToken cancellationToken)
                                                 {
                                                     throw new NotSupportedException();
                                                 }

                                                 protected Task SendRequestAsync(HttpMethod method, string path, object? body, CancellationToken cancellationToken)
                                                 {
                                                     throw new NotSupportedException();
                                                 }

                                                 protected static string WithQuery(string path, params object?[] values)
                                                 {
                                                     return path;
                                                 }

                                                 protected static bool IsNotFound(Exception exception)
                                                 {
                                                     return false;
                                                 }
                                             }

                                             public static class ServiceClientRegistration
                                             {
                                                 public static IServiceCollection AddServiceClient<TInterface, TClient>(this IServiceCollection services, IConfiguration configuration, string? baseUrl)
                                                     where TInterface : class
                                                     where TClient : class, TInterface
                                                 {
                                                     return services;
                                                 }
                                             }

                                             public record LeaseDto
                                             {
                                                 public required long Id { get; init; }
                                             }

                                             [MagicClient("api/leases", UrlSetting = "Services:Leasing:Url", DefaultUrl = "http://leasing")]
                                             public interface ILeasesClient
                                             {
                                                 [ClientGet("{leaseId}")]
                                                 Task<LeaseDto?> GetLease(long leaseId, long companyId);

                                                 [ClientPut("{leaseId}/renewal-reminder-sent")]
                                                 Task MarkRenewalReminderSent(long leaseId);
                                             }
                                             """;

    [Fact]
    public void ConventionClient_SendsThroughTheNamedBase()
    {
        // Act
        var generatorRunResult = ClientGeneratorRuns.Run(ConventionSubject);

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.Clients;

                     public partial class LeasesClient : global::Acme.Leasing.Clients.ServiceClientBase, global::Acme.Leasing.Clients.ILeasesClient
                     {
                         public LeasesClient(string serviceName) : base(serviceName)
                         {
                         }

                         public async global::System.Threading.Tasks.Task<global::Acme.Leasing.Clients.LeaseDto?> GetLease(long leaseId, long companyId)
                         {
                             try
                             {
                                 return await SendRequestAsync<global::Acme.Leasing.Clients.LeaseDto?>(global::System.Net.Http.HttpMethod.Get, WithQuery("api/leases/" + leaseId.ToString(global::System.Globalization.CultureInfo.InvariantCulture), new { companyId }), null, global::System.Threading.CancellationToken.None);
                             }
                             catch (global::System.Exception exception) when (IsNotFound(exception))
                             {
                                 return null;
                             }
                         }

                         public async global::System.Threading.Tasks.Task MarkRenewalReminderSent(long leaseId)
                         {
                             await SendRequestAsync(global::System.Net.Http.HttpMethod.Put, "api/leases/" + leaseId.ToString(global::System.Globalization.CultureInfo.InvariantCulture) + "/renewal-reminder-sent", new object(), global::System.Threading.CancellationToken.None);
                         }
                     }

                     """, generatorRunResult.GeneratedText("Acme.Leasing.Clients.ILeasesClient.Client.g.cs"));
        var leasesClient = generatorRunResult.OutputCompilation.GetTypeByMetadataName("Acme.Leasing.Clients.LeasesClient")!;
        Assert.Equal("Acme.Leasing.Clients.ServiceClientBase", leasesClient.BaseType!.ToDisplayString());
    }

    [Fact]
    public void ConventionClient_RegistersThroughTheNamedRegistration()
    {
        // Act
        var generatorRunResult = ClientGeneratorRuns.Run(ConventionSubject);

        // Assert
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.Clients;

                     public static class LeasesClientRegistration
                     {
                         /// <summary>Registers LeasesClient as ILeasesClient.</summary>
                         public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddLeasesClient(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, global::Microsoft.Extensions.Configuration.IConfiguration configuration)
                         {
                             return global::Acme.Leasing.Clients.ServiceClientRegistration.AddServiceClient<global::Acme.Leasing.Clients.ILeasesClient, global::Acme.Leasing.Clients.LeasesClient>(services, configuration, configuration["Services:Leasing:Url"] ?? "http://leasing");
                         }
                     }

                     """, generatorRunResult.GeneratedText("Acme.Leasing.Clients.ILeasesClient.Registration.g.cs"));
    }

    [Fact]
    public void FakeBase_WritesAVirtualThrowingMember_ForEachInterfaceMember()
    {
        // Act
        var generatorRunResult = ClientGeneratorRuns.Run("""
                                                         using System;
                                                         using System.Threading.Tasks;
                                                         using MagicCSharp.Testing;

                                                         namespace Acme.Leasing.Clients;

                                                         public interface ILeaseLookup
                                                         {
                                                             string Region { get; set; }

                                                             event EventHandler? RegionChanged;

                                                             Task<string?> FindTenant(long leaseId, bool includeFormer = false);
                                                         }

                                                         public abstract class FakeBase
                                                         {
                                                         }

                                                         [GenerateFakeBase(typeof(ILeaseLookup))]
                                                         public abstract partial class FakeLeaseLookupBase : FakeBase;
                                                         """);

        // Assert
        Assert.Empty(generatorRunResult.Diagnostics);
        Assert.Equal("""
                     // <auto-generated/>
                     #nullable enable

                     namespace Acme.Leasing.Clients;

                     partial class FakeLeaseLookupBase : global::Acme.Leasing.Clients.ILeaseLookup
                     {
                         public virtual string Region
                         {
                             get
                             {
                                 throw new global::MagicCSharp.Testing.NotScriptedException("ILeaseLookup.Region");
                             }
                             set
                             {
                                 throw new global::MagicCSharp.Testing.NotScriptedException("ILeaseLookup.Region");
                             }
                         }

                         public virtual event global::System.EventHandler? RegionChanged
                         {
                             add
                             {
                                 throw new global::MagicCSharp.Testing.NotScriptedException("ILeaseLookup.RegionChanged");
                             }
                             remove
                             {
                                 throw new global::MagicCSharp.Testing.NotScriptedException("ILeaseLookup.RegionChanged");
                             }
                         }

                         public virtual global::System.Threading.Tasks.Task<string?> FindTenant(long leaseId, bool includeFormer = false)
                         {
                             throw new global::MagicCSharp.Testing.NotScriptedException("ILeaseLookup.FindTenant(long, bool)");
                         }
                     }

                     """, generatorRunResult.GeneratedText("Acme.Leasing.Clients.FakeLeaseLookupBase.FakeBase.g.cs"));
    }

    [Fact]
    public void MagicClientGenerator_ReusesItsOutput_WhenAnUnrelatedFileChanges()
    {
        // Arrange
        var generatorRunRequest = new GeneratorRunRequest
        {
            SourceFiles = [GeneratorHarness.Subject(ConventionSubject)],
            OtherGenerators = ClientGeneratorRuns.Generators(),
        };
        var compilation = GeneratorHarness.CreateCompilation(generatorRunRequest.SourceFiles,
            GeneratorHarness.DefaultReferences().AddRange(ClientGeneratorRuns.References()));
        var driver = GeneratorHarness.CreateDriver(generatorRunRequest, true).RunGenerators(compilation);
        var unrelatedFile = CSharpSyntaxTree.ParseText("namespace Acme.Leasing.Clients; public class LeaseNote { }",
            (CSharpParseOptions)compilation.SyntaxTrees.First().Options, "LeaseNote.cs");

        // Act
        driver = driver.RunGenerators(compilation.AddSyntaxTrees(unrelatedFile));

        // Assert
        var outputReasons = driver.GetRunResult()
            .Results.Single(result => result.Generator.GetGeneratorType() == typeof(MagicClientGenerator))
            .TrackedOutputSteps.SelectMany(trackedStep => trackedStep.Value)
            .SelectMany(step => step.Outputs)
            .Select(output => output.Reason)
            .ToArray();
        Assert.NotEmpty(outputReasons);
        Assert.All(outputReasons, reason => Assert.Equal(IncrementalStepRunReason.Cached, reason));
    }
}
