    [Fact]
    public void DalMapping_ReusesItsOutput_WhenAnUnrelatedFileChanges()
    {
        // Arrange
        var generatorRunRequest = Request(Usings + NoteTypes + """
                                                               public partial class NoteDal : BaseIdDal<Note, NoteEdit>
                                                               {
                                                                   public string Text { get; set; } = "";
                                                               }
                                                               """);
        var compilation = GeneratorHarness.CreateCompilation(generatorRunRequest.SourceFiles,
            GeneratorHarness.DefaultReferences().AddRange(DataReferences));
        var driver = GeneratorHarness.CreateDriver(generatorRunRequest, true).RunGenerators(compilation);
        var unrelatedFile = CSharpSyntaxTree.ParseText("namespace Acme.Leasing.Data; public class NoteFormatter { }",
            (CSharpParseOptions)compilation.SyntaxTrees.First().Options, "NoteFormatter.cs");

        // Act
        driver = driver.RunGenerators(compilation.AddSyntaxTrees(unrelatedFile));

        // Assert
        var outputReasons = driver.GetRunResult()
            .Results.Single(result => result.Generator.GetGeneratorType() == typeof(DalMappingGenerator))
            .TrackedOutputSteps.SelectMany(trackedStep => trackedStep.Value)
            .SelectMany(step => step.Outputs)
            .Select(output => output.Reason)
            .ToArray();
        // The Dal pipeline reads with the semantic model, so Roslyn re-reads it on any change; an equal reading is
        // Unchanged, and neither that nor Cached writes the file again.
        Assert.NotEmpty(outputReasons);
        Assert.All(outputReasons, reason => Assert.True(reason == IncrementalStepRunReason.Cached || reason == IncrementalStepRunReason.Unchanged,
            $"The Dal mapping output ran again ({reason})."));
    }

